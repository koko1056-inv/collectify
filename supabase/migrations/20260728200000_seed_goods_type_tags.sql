-- =========================================================
-- グッズタイプのタグを用意する
--
-- 商品名からタグを自動で選ぶ仕組みを入れたが、
-- 「登録済みのタグ名にしか一致させない」作りなので、
-- タグ自体が無いうちは何も埋まらない。
-- よく使うグッズタイプを先に入れて、初日から効くようにする。
--
-- 方針:
-- - グッズタイプは作品に依存しないので content_id は NULL
-- - プルダウンは status = 'approved' しか出さないので approved で入れる
-- - 商品名そのもの（「ねんどろいど」等の商品ライン名）は入れない。
--   タイプとして一般的に通じる名前だけにする
-- - 「カード」「バッジ」のような短すぎる語は入れない。
--   関係ない商品名に当たってしまうため（例:「カードケース」）
-- - 「キーホルダー」と「アクリルキーホルダー」は両方入れてよい。
--   自動選択は長い名前を優先するので、短いほうに引っ張られない
--
-- 何度実行しても増えないように、同じ名前が既にあれば入れない。
-- =========================================================

INSERT INTO public.tags (name, category, content_id, status)
SELECT v.name, 'type', NULL, 'approved'
FROM (
  VALUES
    -- アクリル系
    ('アクリルスタンド'),
    ('アクリルキーホルダー'),
    ('アクリルカード'),
    ('アクリルブロック'),
    ('アクリルジオラマ'),
    ('アクリルチャーム'),
    -- バッジ・ピン
    ('缶バッジ'),
    ('ピンバッジ'),
    -- ぬいぐるみ系
    ('ぬいぐるみ'),
    ('マスコット'),
    -- ストラップ・キーホルダー
    ('ラバーストラップ'),
    ('ラバーキーホルダー'),
    ('ラバーバンド'),
    ('キーホルダー'),
    ('ストラップ'),
    -- 紙もの
    ('クリアファイル'),
    ('ポストカード'),
    ('ブロマイド'),
    ('生写真'),
    ('フォトカード'),
    ('トレーディングカード'),
    ('色紙'),
    ('ミニ色紙'),
    ('下敷き'),
    -- 布・大判
    ('タペストリー'),
    ('ポスター'),
    ('ステッカー'),
    ('シール'),
    -- 立体
    ('フィギュア'),
    ('ドール'),
    -- 生活雑貨
    ('マグカップ'),
    ('グラス'),
    ('クッション'),
    ('ブランケット'),
    ('ミラー'),
    ('パスケース'),
    ('スマホケース'),
    -- 衣類・バッグ
    ('トートバッグ'),
    ('ポーチ'),
    ('Tシャツ'),
    ('パーカー'),
    ('タオル'),
    ('マフラータオル'),
    -- 応援グッズ
    ('うちわ'),
    ('ペンライト')
) AS v(name)
WHERE NOT EXISTS (
  SELECT 1
  FROM public.tags t
  WHERE t.name = v.name
    AND t.category = 'type'
    AND t.content_id IS NULL
);
